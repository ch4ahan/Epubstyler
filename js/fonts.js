const CDN = (repo, file) => `https://cdn.jsdelivr.net/gh/fonts-archive/${repo}/${file}`;
const RAW = (repo, file) => `https://raw.githubusercontent.com/fonts-archive/${repo}/main/${file}`;

async function fetchWithFallback(repo, file, asBuffer) {
  for (const url of [CDN(repo, file), RAW(repo, file)]) {
    try {
      const res = await fetch(url, { mode: 'cors' });
      if (!res.ok) continue;
      return asBuffer ? await res.arrayBuffer() : await res.text();
    } catch (e) { /* 다음 주소로 재시도 */ }
  }
  throw new Error(`다운로드 실패: ${repo}/${file}`);
}

// fonts-archive 저장소의 <Repo>.css 를 파싱해 weight별 woff2 파일 목록을 얻는다.
function parseFontFaces(css) {
  const faces = [];
  const re = /@font-face\s*{([^}]*)}/g;
  let m;
  while ((m = re.exec(css))) {
    const block = m[1];
    const w = /font-weight\s*:\s*([\w]+)/.exec(block);
    const u = /url\(["']?([^"')]+\.woff2)["']?\)/.exec(block);
    if (!u) continue;
    let weight = 400;
    if (w) {
      const v = w[1].toLowerCase();
      weight = v === 'bold' ? 700 : v === 'normal' ? 400 : (parseInt(v, 10) || 400);
    }
    faces.push({ weight, file: u[1].replace(/^\.\//, '').split('/').pop() });
  }
  // 같은 weight 중복 제거
  const seen = new Set();
  return faces.filter(f => !seen.has(f.weight) && seen.add(f.weight));
}

/**
 * 카탈로그 폰트 다운로드 → { name, family, files:[{weight, filename, buffer}] }
 * family는 EPUB 안에서 쓸 이름(한국어 폰트명 그대로).
 */
export async function downloadCatalogFont(entry, onProgress) {
  onProgress?.('폰트 정보 확인 중…');
  const css = await fetchWithFallback(entry.repo, `${entry.repo}.css`, false);
  let faces = parseFontFaces(css);
  if (!faces.length) faces = [{ weight: 400, file: `${entry.repo}.woff2` }];
  const files = [];
  for (const f of faces) {
    onProgress?.(`내려받는 중… (${f.weight})`);
    const buffer = await fetchWithFallback(entry.repo, f.file, true);
    files.push({ weight: f.weight, filename: f.file, buffer });
  }
  return { name: entry.name, family: entry.name, files, source: 'catalog' };
}

/** 업로드 파일 → 폰트 항목 */
export async function fontFromFile(file) {
  const ext = (file.name.split('.').pop() || '').toLowerCase();
  if (!['ttf', 'otf', 'woff', 'woff2'].includes(ext)) {
    throw new Error('ttf, otf, woff, woff2 파일만 추가할 수 있어요.');
  }
  const buffer = await file.arrayBuffer();
  const base = file.name.replace(/\.[^.]+$/, '');
  const safe = base.replace(/[^\w가-힣 _-]/g, '').trim() || 'MyFont';
  return {
    name: safe, family: safe, source: 'upload',
    files: [{ weight: 400, filename: `${safe.replace(/\s+/g, '')}.${ext}`, buffer }],
  };
}

export function fontMediaType(filename) {
  const ext = filename.split('.').pop().toLowerCase();
  return { woff2: 'font/woff2', woff: 'font/woff', ttf: 'font/ttf', otf: 'font/otf' }[ext] || 'application/octet-stream';
}

/** 미리보기·저장 공용 @font-face CSS 생성. urlFor(file)로 경로를 주입한다. */
export function fontFaceCss(font, urlFor) {
  return font.files.map(f =>
`@font-face {
  font-family: "${font.family}";
  src: url("${urlFor(f)}");
  font-weight: ${f.weight};
  font-display: swap;
}`).join('\n');
}
